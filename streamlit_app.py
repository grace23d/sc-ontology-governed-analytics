# ------------------------------------------------------------------ Governance
with tab_gov:
    st.subheader("Change a certified definition")
    st.write("Definitions change in one governed place. A change needs a reason, bumps the version, "
             "re-applies the rules and updates every persona's answer at once. Every change is logged.")
    st.session_state.setdefault("last_change", None)
    try:
        params = run_sql(f"SELECT param_name, param_value, unit, used_by, description, version, "
                         f"min_value, max_value, whole_number, updated_at "
                         f"FROM {DB}.GOVERNED.METRIC_PARAMETER ORDER BY param_name")
        st.dataframe(params, use_container_width=True)

        pname = st.selectbox("Parameter", params["PARAM_NAME"].tolist())
        prow = params[params["PARAM_NAME"] == pname].iloc[0]
        whole = bool(prow["WHOLE_NUMBER"]) if pd.notna(prow["WHOLE_NUMBER"]) else False
        with st.form(f"change_form_{pname}"):
            new_val = st.number_input(
                f"New value ({prow['UNIT']}; currently {float(prow['PARAM_VALUE']):g})",
                min_value=float(prow["MIN_VALUE"]) if pd.notna(prow["MIN_VALUE"]) else 0.0,
                max_value=float(prow["MAX_VALUE"]) if pd.notna(prow["MAX_VALUE"]) else 1000.0,
                value=float(prow["PARAM_VALUE"]), step=1.0 if whole else 0.1)
            reason = st.text_input("Reason for the change",
                                   placeholder="For example: Procurement aligning with new supplier contract terms")
            go = st.form_submit_button("Apply governed change")
        if go:
            with st.spinner("Updating the definition and re-applying rules"):
                raw = session.sql(f"CALL {DB}.GOVERNED.SP_CHANGE_METRIC_PARAMETER(?, ?, ?, ?)",
                                  params=[pname, float(new_val), reason, viewer_name()]).collect()[0][0]
            st.session_state.last_change = json.loads(raw) if isinstance(raw, str) else dict(raw)
            load_governed.clear()
            rerun()

        lc = st.session_state.last_change
        if lc:
            if lc.get("status") == "APPLIED":
                st.success(f"{lc['param_name']}: {float(lc['old_value']):g} → {float(lc['new_value']):g}. "
                           f"Version {lc['old_version']} → {lc['new_version']}.")
                before, after = lc.get("before") or {}, lc.get("after") or {}
                moved = pd.DataFrame([
                    {"Metric": k, "Before": fmt(before.get(k)), "After": fmt(after.get(k)),
                     "Changed": "yes" if not matches(after.get(k), before.get(k)) else ""}
                    for k in sorted(set(before) | set(after))])
                st.write("Certified scorecard (Chennai), before and after. Every persona now gets the 'After' value.")
                st.dataframe(moved, use_container_width=True)
            else:
                st.warning(f"{lc.get('status')}: {lc.get('message')}")

        st.subheader("Change log")
        log = run_sql(
            f"SELECT changed_at, changed_by, param_name, metric_id, old_value, new_value, old_version, new_version, "
            f"reason, scorecard_before:supplier_otd::FLOAT AS supplier_otd_before, "
            f"scorecard_after:supplier_otd::FLOAT AS supplier_otd_after "
            f"FROM {DB}.GOVERNED.METRIC_CHANGE_LOG ORDER BY changed_at DESC LIMIT 20")
        if log.empty:
            st.info("No changes yet.")
        else:
            st.dataframe(log, use_container_width=True)
            last = log.iloc[0]
            if st.button(f"Revert the last change ({last['PARAM_NAME']} back to {float(last['OLD_VALUE']):g})"):
                raw = session.sql(f"CALL {DB}.GOVERNED.SP_CHANGE_METRIC_PARAMETER(?, ?, ?, ?)",
                                  params=[last["PARAM_NAME"], float(last["OLD_VALUE"]),
                                          f"Revert of change made at {last['CHANGED_AT']}", viewer_name()]
                                  ).collect()[0][0]
                st.session_state.last_change = json.loads(raw) if isinstance(raw, str) else dict(raw)
                load_governed.clear()
                rerun()
    except Exception as exc:
        st.info(f"Run 09_definition_change.sql to enable governed changes. ({exc})")

