def _wrap(text: str, width: int = 18) -> str:
    """Break an axis label into lines (joined with '|', split again by the chart)."""
    lines, cur = [], ""
    for word in str(text).split():
        if cur and len(cur) + 1 + len(word) > width:
            lines.append(cur)
            cur = word
        else:
            cur = f"{cur} {word}".strip()
    lines.append(cur)
    return "|".join(lines)


def waterfall_chart(part: pd.DataFrame) -> alt.Chart:
    """Legacy bar, one bar per rule (gain or loss), certified total bar."""
    part = part.sort_values("STEP_NO")
    values = part["VALUE"].astype(float).tolist()
    lo = max(0.0, min(values) - 0.08)
    hi = min(1.0, max(values) + 0.04)
    rows, prev = [], None
    for _, r in part.iterrows():
        v = float(r["VALUE"])
        label = f"{int(r['STEP_NO'])}. {r['STEP_LABEL']}"
        if prev is None:
            rows.append(dict(step=label, start=lo, end=v, kind="Legacy", text=f"{v:.1%}", rule=r["RULE_APPLIED"]))
        else:
            d = v - prev
            rows.append(dict(step=label, start=prev, end=v, kind="Raises" if d >= 0 else "Lowers",
                             text=f"{d * 100:+.1f} pts", rule=r["RULE_APPLIED"]))
        prev = v
    rows.append(dict(step="Certified value", start=lo, end=prev, kind="Certified", text=f"{prev:.1%}",
                     rule="The number every persona gets"))
    data = pd.DataFrame(rows)
    data["top"] = data[["start", "end"]].max(axis=1)
    data["step"] = data["step"].map(_wrap)
    order = data["step"].tolist()
    colour = alt.Scale(domain=["Legacy", "Raises", "Lowers", "Certified"], range=[C_LEGACY, C_UP, C_DOWN, C_CERT])
    base = alt.Chart(data).encode(x=alt.X("step:N", sort=order, title=None,
                                          axis=alt.Axis(labelAngle=0, labelLimit=200,
                                                        labelExpr="split(datum.label, '|')")))
    bars = base.mark_bar(size=38, clip=True).encode(
        y=alt.Y("start:Q", scale=alt.Scale(domain=[lo, hi]), axis=alt.Axis(format="%", title=None)),
        y2="end:Q",
        color=alt.Color("kind:N", scale=colour, legend=alt.Legend(title=None, orient="top")),
        tooltip=[alt.Tooltip("step:N", title="Step"), alt.Tooltip("text:N", title="Effect"),
                 alt.Tooltip("rule:N", title="Rule")],
    )
    labels = base.mark_text(dy=-8, fontSize=12).encode(y=alt.Y("top:Q", scale=alt.Scale(domain=[lo, hi])),
                                                       text="text:N")
    return (bars + labels).properties(height=320)


def ontology_dot(registry: pd.DataFrame) -> str:
    """Entities and relationships as declared in the semantic view, with certified metrics on their home entity."""
    dims = {"suppliers": "Supplier", "parts": "Part", "plants": "Plant", "customers": "Customer", "carriers": "Carrier"}
    facts = {"po_lines": "PO line", "order_lines": "Order line", "shipments": "Shipment", "inventory": "Inventory"}
    edges = [("po_lines", "suppliers", "supplied by"), ("po_lines", "parts", "for part"), ("po_lines", "plants", "received at"),
             ("order_lines", "customers", "placed by"), ("order_lines", "parts", "for part"),
             ("order_lines", "plants", "fulfilled from"), ("order_lines", "carriers", "primary carrier"),
             ("shipments", "customers", "delivered to"), ("shipments", "parts", "carries part"),
             ("shipments", "plants", "ships from"), ("shipments", "carriers", "carried by"),
             ("inventory", "parts", "stock of"), ("inventory", "plants", "held at")]
    lines = ['digraph G {', 'rankdir=LR; bgcolor="transparent"; nodesep=0.35; ranksep=0.9;',
             'node [fontname="Helvetica", fontsize=11, style="rounded,filled", shape=box, penwidth=0];',
             'edge [fontname="Helvetica", fontsize=9, color="#8a8a86", fontcolor="#6b6b67"];']
    for k, v in facts.items():
        lines.append(f'{k} [label="{v}", fillcolor="#184f95", fontcolor="white"];')
    for k, v in dims.items():
        lines.append(f'{k} [label="{v}", fillcolor="#cde2fb", fontcolor="#0d366b"];')
    for a, b, lbl in edges:
        lines.append(f'{a} -> {b} [label="{lbl}"];')
    lines.append('shipments -> order_lines [label="fulfils (conformed layer)", style=dashed];')
    for _, r in registry.iterrows():
        home = str(r["SEMANTIC_METRIC"]).split(".")[0]
        mid = "m_" + str(r["METRIC_ID"])
        lines.append(f'{mid} [label="{r["DISPLAY_NAME"]}\\nv{r["VERSION"]}", shape=note, '
                     f'fillcolor="#f0efec", fontcolor="#1a1a19", fontsize=9];')
        lines.append(f'{home} -> {mid} [arrowhead=none, style=dotted];')
    lines.append("}")
    return "\n".join(lines)


