def run_sql(sql: str, params: list | None = None) -> pd.DataFrame:
    df = session.sql(sql.strip().rstrip(";"), params=params).to_pandas() if params \
        else session.sql(sql.strip().rstrip(";")).to_pandas()
    df.columns = [str(c).upper() for c in df.columns]
    return df


WRITE_WORDS = re.compile(
    r"\b(INSERT|UPDATE|DELETE|MERGE|DROP|TRUNCATE|CREATE|ALTER|GRANT|REVOKE|CALL|COPY|PUT|GET|REMOVE|"
    r"EXECUTE|UNDROP|USE|SET|UNSET)\b", re.I)


def is_read_only(sql: str | None) -> bool:
    """Only single SELECT / WITH statements generated by the NL layer are ever executed."""
    body = re.sub(r"--[^\n]*|/\*.*?\*/", " ", sql or "", flags=re.S)
    body = re.sub(r"'(?:[^']|'')*'", "''", body).strip().rstrip(";").strip()
    if not body:
        return False
    first = body.split(None, 1)[0].upper()
    return first in ("SELECT", "WITH") and ";" not in body and not WRITE_WORDS.search(body)


# ------------------------------------------------------------ Cortex Analyst
SPCS_TOKEN_FILE = "/snowflake/session/token"


def _rest_target():
    """Host and auth headers for calling the Snowflake REST API from the container runtime."""
    if os.path.exists(SPCS_TOKEN_FILE):
        with open(SPCS_TOKEN_FILE) as f:
            token = f.read().strip()
        host = os.environ.get("SNOWFLAKE_HOST") or session.connection.host
        headers = {"Authorization": f"Bearer {token}",
                   "X-Snowflake-Authorization-Token-Type": "OAUTH"}
    else:
        host = session.connection.host
        headers = {"Authorization": f'Snowflake Token="{session.connection.rest.token}"'}
    headers.update({"Content-Type": "application/json", "Accept": "application/json"})
    return host, headers


def call_analyst(messages: list) -> dict:
    body = {"messages": messages, "semantic_view": SEMANTIC_VIEW}
    if _snowflake is not None:
        resp = _snowflake.send_snow_api_request(
            "POST", ANALYST_ENDPOINT, {}, {}, body, None, ANALYST_TIMEOUT_MS
        )
        status, parsed = resp["status"], json.loads(resp["content"])
    else:
        host, headers = _rest_target()
        r = requests.post(f"https://{host}{ANALYST_ENDPOINT}", json=body, headers=headers,
                          timeout=ANALYST_TIMEOUT_MS / 1000)
        status = r.status_code
        try:
            parsed = r.json()
        except ValueError:
            parsed = {"message": r.text[:500]}
    if status >= 400:
        raise RuntimeError(f"Cortex Analyst returned {status}: {parsed.get('message', parsed)}")
    return parsed


def parse_analyst(parsed: dict) -> dict:
    out = {"text": [], "sql": None, "suggestions": [], "verified_query": None,
           "request_id": parsed.get("request_id"), "raw_message": parsed.get("message")}
    for item in (parsed.get("message") or {}).get("content", []):
        kind = item.get("type")
        if kind == "text":
            out["text"].append(item.get("text", ""))
        elif kind == "sql":
            out["sql"] = item.get("statement")
            vq = (item.get("confidence") or {}).get("verified_query_used")
            if vq:
                out["verified_query"] = vq.get("name") or vq.get("question") or "yes"
        elif kind == "suggestions":
            out["suggestions"].extend(item.get("suggestions", []))
    return out


def ask(question: str, history: list | None = None):
    msgs = list(history or []) + [{"role": "user", "content": [{"type": "text", "text": question}]}]
    return parse_analyst(call_analyst(msgs)), msgs


# ------------------------------------------------------------------ helpers
def short_name(semantic_metric: str) -> str:
    return semantic_metric.split(".")[-1].lower()


def detect_metrics(sql: str | None, texts: list, registry: pd.DataFrame) -> list:
    hay = f"{sql or ''} {' '.join(texts or [])}".lower()
    return [r for _, r in registry.iterrows() if short_name(r["SEMANTIC_METRIC"]) in hay]


def to_scalar(df: pd.DataFrame | None, hint: str | None = None):
    """Return the single numeric answer from a one-row result."""
    if df is None or df.empty or len(df) != 1:
        return None
    candidates = []
    for col in df.columns:
        val = pd.to_numeric(df[col], errors="coerce")
        if val.notna().all():
            candidates.append((col, float(val.iloc[0])))
    if not candidates:
        return None
    if hint:
        for col, v in candidates:
            if hint.lower() in str(col).lower():
                return v
    return candidates[-1][1]


def normalise(value, expected):
    """If a ratio came back as a percentage, scale it back and say so."""
    if value is None or expected is None:
        return value, False
    if abs(expected) <= 1.5 and 1.5 < abs(value) <= 150:
        return value / 100, True
    return value, False


def matches(value, expected) -> bool:
    if value is None or expected is None:
        return False
    tol = RATIO_TOLERANCE if abs(expected) <= 1.5 else abs(expected) * 1e-6
    return abs(value - expected) <= tol


def fmt(value, expected=None) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "no value"
    ref = expected if expected is not None else value
    return f"{value:.2%}" if abs(ref) <= 1.5 else f"{value:,.2f}"


def audit(persona, question, res, metrics, outcome):
    try:
        session.sql(
            f"INSERT INTO {DB}.GOVERNED.QUERY_AUDIT_LOG "
            "(persona, question, generated_sql, metrics_resolved, verified_query_used, analyst_request_id, outcome) "
            "SELECT ?, ?, ?, ?, ?, ?, ?",
            params=[persona, question, res.get("sql"), ",".join(metrics),
                    res.get("verified_query"), res.get("request_id"), outcome],
        ).collect()
    except Exception as exc:  # audit must never break the answer
        st.caption(f"Audit log write skipped: {exc}")


